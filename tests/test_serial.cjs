const assert = require('node:assert/strict');
const {crc,frame,response,parse,Controller} = require('../fluixer/ui/serial-controller.js');
const header='type,motor,direction,steps,speed,unit,seconds\n';
(async()=>{
  assert.equal(crc('123456789'),0xF4);
  assert.equal(response(frame('OK 1.0').trim()),'1.0');
  assert.throws(()=>response('OK *00'));
  assert.throws(()=>response('ERR 01 checksum'));
  for(const line of ['move,g,fwd,0,400,steps,','move,g,fwd,2.5,400,steps,','move,g,fwd,2001,400,steps,','move,g,fwd,90,400,segments,','move,g,fwd,1,626,steps,','move,x,fwd,1,400,steps,','delay,,,,,,11']) assert.throws(()=>parse(header+line));
  const rows=parse('\ufeff'+header+'move,l,fwd,3,400,segments,\nmove,g,rev,100,300,steps,\ndelay,,,,,,0.01');
  const c=new Controller(), sent=[], progress=[]; c.ready=true;
  c.command=async command=>{sent.push(command);return '';};
  await c.run(rows,(i)=>progress.push(i));
  assert.deepEqual(sent,['MOV 1 l fwd 67 400','MOV 1 l fwd 67 400','MOV 1 l fwd 66 400','MOV 1 g rev 100 300']);
  assert.deepEqual(progress,[1,2,3]);
  const p=new Controller();p.ready=true;let release;let count=0;
  p.command=()=>{count++;return new Promise(r=>release=r)};
  const running=p.run([rows[1],rows[1]],()=>{});
  await new Promise(r=>setTimeout(r,0));p.paused=true;release();
  await new Promise(r=>setTimeout(r,50));assert.equal(count,1);
  p.paused=false;await new Promise(r=>setTimeout(r,50));assert.equal(count,2);release();await running;
  const normal=new Controller(); normal.ready=true;
  const port={}; normal.port=port; let ack, sentCount=0;
  normal.command=()=>{sentCount++;return new Promise(resolve=>ack=resolve)};
  const job=normal.run([rows[1],rows[1]],()=>{});
  await new Promise(r=>setTimeout(r,0)); normal.stop();
  assert.equal(normal.running,true,'wait for current command');
  assert.equal(normal.ready,true); assert.equal(normal.port,port);
  ack(); await job;
  assert.equal(sentCount,1,'no next command'); assert.equal(normal.running,false);
  assert.equal(normal.stopping,false); assert.equal(normal.ready,true); assert.equal(normal.port,port);
  normal.command=async()=>{sentCount++};
  await normal.run([rows[1]],()=>{}); assert.equal(sentCount,2,'restart without reconnect');
  const delayed=new Controller(); delayed.ready=true; delayed.port=port;
  const delayJob=delayed.run([{seconds:1}],()=>{});
  await new Promise(r=>setTimeout(r,0)); delayed.paused=true; delayed.stop(); await delayJob;
  assert.equal(delayed.ready,true); assert.equal(delayed.port,port);
  const failure=new Controller();failure.ready=true;const writes=[];
  failure.writer={write:async bytes=>{writes.push(new TextDecoder().decode(bytes));},releaseLock(){}};
  failure.command=async()=>{throw Error('Timeout')};
  await failure.run([rows[1],rows[1]],()=>{throw Error('Must not advance')});
  assert.deepEqual(writes,[frame('ESTP')]);assert.equal(failure.ready,false);
  const fast=new Controller();
  fast.writer={write:async()=>fast.pending.resolve('immediate')};
  assert.equal(await fast.command('VER',100),'immediate');
  fast.writer={write:async()=>{}};
  await assert.rejects(fast.command('VER',5),/timed out/);
  assert.equal(fast.pending,null);
  console.log('PASS: CSV validation, CRC, segment expansion, ordered ACKs, pause, timeout, emergency stop.');
})().catch(error=>{console.error(error);process.exitCode=1});
